"""Minimal UI translation: `tr("English text", **fmt)` looks the text up in the Ukrainian catalog.

English is the source language and the default; a missing catalog entry falls back to English.
Placeholders use str.format syntax, so f-strings become `tr("Note {name}", name=...)`.
Every `tr()` call must pass a string literal so tests/test_i18n.py can check it against `UK`."""
from __future__ import annotations

LANGUAGES = {"en": "English", "uk": "Українська"}   # code -> name shown in the switcher (always in its own language)

_lang = "en"


def set_language(code: str) -> None:
    global _lang
    _lang = code if code in LANGUAGES else "en"


def language() -> str:
    return _lang


def tr(text: str, **fmt) -> str:
    out = UK.get(text, text) if _lang == "uk" else text
    return out.format(**fmt) if fmt else out


